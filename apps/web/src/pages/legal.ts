const APP_TITLE = "ここ暇";

/** 開いている間だけ、タブの題を「<題>｜ここ暇」にする。離れたら「ここ暇」に戻す */
export function useDocumentTitle(title: string) {
  useEffect(() => {
    document.title = `${title}｜${APP_TITLE}`;
    return () => {
      document.title = APP_TITLE;
    };
  }, [title]);
}
